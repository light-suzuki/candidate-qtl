# A run whose every response is the same bytes cannot demonstrate the
# per-prompt evaluation the canonical benchmark contract requires: it is
# exactly what a loop that never reads the prompt produces.  On a tiny roster
# uniformity carries no signal -- three thin units genuinely can all be
# abstentions -- so the verdict is only asserted once the roster is large
# enough for the coincidence to mean something.
UNIFORM_RESPONSE_MIN_PROMPTS = 5
EXECUTION_EVIDENCE_VARIED = "per_prompt_variation"
EXECUTION_EVIDENCE_UNIFORM = "uniform_responses_not_distinguishable_from_runner_output"
EXECUTION_EVIDENCE_SMALL_ROSTER = "roster_too_small_to_assess"


def response_execution_evidence(normalized: list[dict[str, object]]) -> dict[str, object]:
    """Summarise whether a response set can evidence per-prompt evaluation.

    This does not judge the answers.  It reports one fact a consumer cannot
    otherwise recover from hashes alone: how many distinct response bodies the
    roster actually contains.  ``CORE-README`` section 10 makes the empty-claim
    abstention valid only for a real model or agent that evaluated every frozen
    prompt one-to-one, and explicitly refuses to count a run whose empty
    responses were generated by the runner.  A single distinct body across a
    full roster is that refusal condition, so name it here rather than leaving
    every downstream reader to re-derive it.
    """
    bodies = {str(item.get("raw_text", "")) for item in normalized}
    empty_claims = sum(
        1 for item in normalized
        if not (item.get("claims") if isinstance(item.get("claims"), list) else [])
    )
    prompt_count = len(normalized)
    if prompt_count < UNIFORM_RESPONSE_MIN_PROMPTS:
        evidence = EXECUTION_EVIDENCE_SMALL_ROSTER
    elif len(bodies) == 1:
        evidence = EXECUTION_EVIDENCE_UNIFORM
    else:
        evidence = EXECUTION_EVIDENCE_VARIED
    return {
        "distinct_response_count": len(bodies),
        "empty_claim_response_count": empty_claims,
        "execution_evidence": evidence,
        "counts_as_per_prompt_evaluation": evidence == EXECUTION_EVIDENCE_VARIED,
    }


