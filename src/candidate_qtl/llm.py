def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export_llm_prompts(packet_arg: str, out_arg: str) -> dict[str, object]:
    """Convert a research packet to stable, provider-neutral JSONL prompts."""
    packet_path = runtime_path(packet_arg)
    output = runtime_path(out_arg)
    payload = json.loads(packet_path.read_text(encoding="utf-8"))
    candidates = payload.get("candidates", [])
    if not isinstance(candidates, list):
        raise ValueError("research packet must contain a candidates list")
    output.parent.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, object]] = []
    for index, candidate in enumerate(candidates, 1):
        if not isinstance(candidate, dict) or not candidate.get("gene_id"):
            raise ValueError("each research packet candidate requires gene_id")
        gene_id = str(candidate["gene_id"])
        user_prompt = (
            f"Review candidate {gene_id} for trait {candidate.get('trait', payload.get('trait', ''))} "
            f"in {candidate.get('species', payload.get('species', ''))}.\n\n"
            "Candidate packet:\n"
            + json.dumps(candidate, ensure_ascii=False, indent=2)
        )
        rows.append(
            {
                "prompt_id": f"candidate-{index:04d}-{gene_id}",
                "gene_id": gene_id,
                "system": SYSTEM_PROMPT,
                "user": user_prompt,
                "source_packet": str(packet_path),
            }
        )
    with output.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    manifest = {
        "source_packet": str(packet_path),
        "prompts": str(output),
        "prompt_count": len(rows),
        "contains_sequences": False,
        "warning": "Inspect JSONL before external API use. The workflow never imports model claims without human review.",
    }
    manifest_path = output.with_suffix(output.suffix + ".manifest.json")
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return manifest | {"manifest": str(manifest_path)}


def export_shortlist_review_prompt(packet_arg: str, out_arg: str) -> dict[str, object]:
    """Export one blinded prompt that compares every member of a frozen shortlist."""
    packet_path = runtime_path(packet_arg)
    output = runtime_path(out_arg)
    payload = json.loads(packet_path.read_text(encoding="utf-8"))
    candidates = payload.get("candidates", [])
    if not isinstance(candidates, list) or not candidates:
        raise ValueError("research packet must contain a non-empty candidates list")
    gene_ids = [str(item.get("gene_id", "")) for item in candidates if isinstance(item, dict)]
    if len(gene_ids) != len(candidates) or any(not gene_id for gene_id in gene_ids):
        raise ValueError("every shortlist candidate requires gene_id")
    if len(set(gene_ids)) != len(gene_ids):
        raise ValueError("shortlist gene IDs must be unique")
    compact_candidates = []
    candidate_keys = {
        "gene_id", "description", "chrom", "start", "end", "dry_score",
        "screening_rank", "top_eligibility",
        "support_family_count", "independent_source_count", "rescue_reason",
    }
    evidence_keys = {
        "evidence_code", "direction", "confidence", "value", "source_id",
        "reviewed",
    }
    literature_keys = {"title", "year", "doi", "pmid"}
    for item in candidates:
        compact_candidates.append({
            "gene_id": item["gene_id"],
            "candidate": {
                key: value for key, value in item.get("candidate", {}).items()
                if key in candidate_keys and str(value).strip()
            },
            "evidence": [
                {key: value for key, value in row.items() if key in evidence_keys and str(value).strip()}
                for row in item.get("evidence", [])
            ],
            "literature": [
                {key: value for key, value in row.items() if key in literature_keys and str(value).strip()}
                for row in item.get("literature", [])[:2]
            ],
        })
    record = {
        "prompt_id": "shortlist-stage-b-review",
        "gene_id": "__frozen_shortlist__",
        "system": SHORTLIST_SYSTEM_PROMPT,
        "user": (
            f"Species: {payload.get('species', '')}\nTrait: {payload.get('trait', '')}\n"
            f"Frozen Stage-A size: {len(candidates)}\n"
            f"Required gene IDs (exact set, no duplicates): {json.dumps(gene_ids)}\n"
            f"Return exactly {len(candidates)} ranking objects and silently verify ranks and IDs before answering.\n\nCandidate packets:\n"
            + json.dumps(compact_candidates, ensure_ascii=False, separators=(",", ":"))
        ),
        "source_packet": str(packet_path),
        "frozen_gene_ids": gene_ids,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(record, ensure_ascii=False) + "\n", encoding="utf-8")
    manifest = {
        "source_packet": str(packet_path), "prompts": str(output),
        "prompt_count": 1, "candidate_count": len(candidates),
        "frozen_gene_ids": gene_ids, "contains_sequences": False,
        "stage": "B_optional_llm_review", "llm_may_overwrite_stage_a": False,
    }
    manifest_path = output.with_suffix(output.suffix + ".manifest.json")
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return manifest | {"manifest": str(manifest_path)}


def import_shortlist_review(shortlist_arg: str, responses_arg: str, out_dir_arg: str) -> dict[str, object]:
    """Validate a model review against the exact Stage-A candidate set."""
    shortlist_path = runtime_path(shortlist_arg)
    responses_path = runtime_path(responses_arg)
    out_dir = runtime_path(out_dir_arg)
    out_dir.mkdir(parents=True, exist_ok=True)
    shortlist = pd.read_csv(shortlist_path, sep="\t", dtype=str).fillna("")
    if "gene_id" not in shortlist.columns:
        raise ValueError("shortlist must contain gene_id")
    expected = list(shortlist["gene_id"])
    payload = json.loads(responses_path.read_text(encoding="utf-8"))
    records = payload.get("candidates", [])
    if len(records) != 1 or not isinstance(records[0], dict):
        raise ValueError("shortlist review requires exactly one batch model response")
    model_json = records[0].get("model_json")
    ranking = model_json.get("ranking") if isinstance(model_json, dict) else None
    if not isinstance(ranking, list):
        raise ValueError("model response must contain a ranking list")
    frame = pd.DataFrame(ranking)
    required = {"gene_id", "rank", "rationale", "source_ids", "wet_test"}
    if not required.issubset(frame.columns):
        raise ValueError("model ranking is missing required fields")
    if set(frame["gene_id"].astype(str)) != set(expected) or len(frame) != len(expected):
        raise ValueError("model ranking must contain exactly the frozen Stage-A gene set")
    ranks = pd.to_numeric(frame["rank"], errors="raise").astype(int)
    if sorted(ranks.tolist()) != list(range(1, len(expected) + 1)):
        raise ValueError("model ranks must be unique consecutive integers beginning at 1")
    frame["rank"] = ranks
    frame["source_ids"] = frame["source_ids"].map(
        lambda value: ";".join(str(item) for item in value) if isinstance(value, list) else str(value)
    )
    frame["reviewed"] = False
    frame["scoring_evidence"] = False
    frame = frame.sort_values("rank", kind="stable")
    ranking_path = out_dir / "llm_review_ranking.tsv"
    frame.to_csv(ranking_path, sep="\t", index=False)
    manifest = {
        "stage": "B_optional_llm_review",
        "shortlist": str(shortlist_path), "responses": str(responses_path),
        "candidate_count": len(frame), "candidate_set_preserved": True,
        "llm_may_overwrite_stage_a": False, "reviewed": False,
        "interpretation": "LLM ordering is an unreviewed reading aid, not causal evidence.",
    }
    manifest_path = out_dir / "llm_review_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"ranking": str(ranking_path), "manifest": str(manifest_path), "candidate_count": len(frame)}


def benchmark_shortlist_reviews(config_arg: str, out_dir_arg: str) -> dict[str, object]:
    """Compare deterministic order with LLM reviews on the same frozen set."""
    import hashlib

    config_path = runtime_path(config_arg)
    out_dir = runtime_path(out_dir_arg)
    out_dir.mkdir(parents=True, exist_ok=True)
    config = pd.read_csv(config_path, sep="\t", dtype=str).fillna("")
    required = {
        "case_id", "truth_gene_ids", "shortlist",
        "no_research_ranking", "api_research_ranking",
    }
    if not required.issubset(config.columns):
        raise ValueError("review benchmark config is missing required columns")
    rows = []
    for item in config.itertuples():
        truths = {value.strip() for value in item.truth_gene_ids.split("|") if value.strip()}
        shortlist = pd.read_csv(runtime_path(item.shortlist), sep="\t", dtype=str).fillna("")
        if "deterministic_review_order" not in shortlist.columns:
            raise ValueError("shortlist requires deterministic_review_order")
        profiles = {
            "deterministic_stage_a": shortlist[["gene_id", "deterministic_review_order"]].rename(
                columns={"deterministic_review_order": "rank"}
            ),
            "llm_no_api_research": pd.read_csv(runtime_path(item.no_research_ranking), sep="\t", dtype=str).fillna("")[["gene_id", "rank"]],
            "llm_with_api_research": pd.read_csv(runtime_path(item.api_research_ranking), sep="\t", dtype=str).fillna("")[["gene_id", "rank"]],
        }
        expected = set(shortlist["gene_id"])
        for profile, ranking in profiles.items():
            if set(ranking["gene_id"]) != expected or len(ranking) != len(expected):
                raise ValueError(f"{item.case_id} {profile} changed the frozen candidate set")
            ranking = ranking.copy()
            ranking["rank"] = pd.to_numeric(ranking["rank"], errors="raise").astype(int)
            truth_ranks = ranking.loc[ranking["gene_id"].isin(truths), "rank"]
            rank = int(truth_ranks.min()) if len(truth_ranks) else None
            rows.append({
                "case_id": item.case_id, "review_profile": profile,
                "candidate_count": len(expected), "truth_gene_ids": item.truth_gene_ids,
                "truth_covered": rank is not None, "truth_rank": rank,
                "top1": rank is not None and rank <= 1,
                "top5": rank is not None and rank <= 5,
                "top10": rank is not None and rank <= 10,
                "top20": rank is not None and rank <= 20,
            })
    detail = pd.DataFrame(rows)
    detail_path = out_dir / "llm_review_benchmark.tsv"
    detail.to_csv(detail_path, sep="\t", index=False)
    summary = detail.groupby("review_profile", sort=False).agg(
        case_count=("case_id", "size"),
        top1_recall=("top1", "mean"), top5_recall=("top5", "mean"),
        top10_recall=("top10", "mean"), top20_recall=("top20", "mean"),
        median_truth_rank=("truth_rank", "median"),
    ).reset_index()
    summary_path = out_dir / "llm_review_benchmark_summary.tsv"
    summary.to_csv(summary_path, sep="\t", index=False)
    report = [
        "# Optional LLM Stage-B review pilot", "",
        "All profiles receive the exact same deterministic Stage-A shortlist. LLM ranks are unreviewed reading aids and never scoring evidence.", "",
        "| profile | n | Top-1 | Top-5 | median truth rank |", "|---|---:|---:|---:|---:|",
    ]
    for row in summary.itertuples():
        report.append(
            f"| {row.review_profile} | {int(row.case_count)} | {row.top1_recall:.3f} | {row.top5_recall:.3f} | {row.median_truth_rank:.1f} |"
        )
    report.extend(["", "This small pilot is not a general performance estimate; the non-LLM known-gene benchmark remains the primary validation."])
    report_path = out_dir / "llm_review_benchmark_report.md"
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")
    manifest = {
        "stage_a_set_changed": False, "llm_scoring_evidence": False,
        "causal_probability": False, "case_count": int(config["case_id"].nunique()),
        "config": str(config_path),
        "config_sha256": hashlib.sha256(config_path.read_bytes()).hexdigest(),
        "warning": "Small, selected known-gene pilot; do not generalize beyond these cases.",
    }
    manifest_path = out_dir / "llm_review_benchmark_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"detail": str(detail_path), "summary": str(summary_path), "report": str(report_path), "manifest": str(manifest_path)}


def _is_loopback(endpoint: str) -> bool:
    host = (urlparse(endpoint).hostname or "").casefold()
    return host in {"localhost", "127.0.0.1", "::1"}


def _response_text(provider: str, payload: dict[str, object]) -> str:
    if provider == "openai-responses":
        chunks: list[str] = []
        for item in payload.get("output", []) if isinstance(payload.get("output"), list) else []:
            if not isinstance(item, dict):
                continue
            for content in item.get("content", []) if isinstance(item.get("content"), list) else []:
                if isinstance(content, dict) and content.get("type") == "output_text":
                    chunks.append(str(content.get("text", "")))
        return "\n".join(chunks)
    choices = payload.get("choices", [])
    if isinstance(choices, list) and choices and isinstance(choices[0], dict):
        message = choices[0].get("message", {})
        if isinstance(message, dict):
            return str(message.get("content", ""))
    return ""


def _parse_model_json(text: str) -> object | None:
    # lms chat emits cursor/color control sequences even when stdout is
    # captured. Strip terminal controls before validating the JSON payload.
    cleaned = re.sub(r"\x1b\[[0-?]*[ -/]*[@-~]", "", text).strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        return None


def _canonical_json_text(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _read_agent_payload(path: Path) -> object:
    """Read one offline agent artifact without changing its source bytes."""
    text = path.read_text(encoding="utf-8")
    try:
        return json.loads(text)
    except json.JSONDecodeError as error:
        # A JSONL file is useful for agent handoff, but every non-empty line must
        # still be independently valid JSON.  Never salvage only the valid rows.
        records: list[object] = []
        for line_number, line in enumerate(text.splitlines(), 1):
            if not line.strip():
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as line_error:
                raise ValueError(
                    f"offline agent file is not valid JSON/JSONL at line {line_number}: {line_error.msg}"
                ) from line_error
        if records:
            return records
        raise ValueError(f"offline agent file is not valid JSON: {error.msg}") from error


def _agent_response_records(payload: object) -> list[object]:
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        if str(payload.get("prompt_id", "")).strip():
            return [payload]
        present = [key for key in ("responses", "candidates") if key in payload]
        if len(present) != 1:
            raise ValueError(
                "offline agent file must be a top-level array or contain exactly one of responses/candidates"
            )
        records = payload[present[0]]
        if not isinstance(records, list):
            raise ValueError(f"offline agent file field {present[0]} must be a list")
        return records
    raise ValueError("offline agent file must be a top-level array or an object with responses/candidates")


def _agent_model_json(record: dict[str, object], prompt_id: str) -> tuple[str, object]:
    """Validate raw/model fields and return the preserved text plus parsed JSON."""
    values: list[tuple[str, object]] = []
    raw_text = record.get("raw_text")
    if raw_text is not None:
        if not isinstance(raw_text, str) or not raw_text.strip():
            raise ValueError(f"offline response {prompt_id} raw_text must be a non-empty string")
        parsed = _parse_model_json(raw_text)
        if parsed is None:
            raise ValueError(f"offline response {prompt_id} raw_text is not valid JSON")
        values.append(("raw_text", parsed))

    if "model_json" in record:
        model_json = record["model_json"]
        if model_json is None:
            raise ValueError(f"offline response {prompt_id} model_json cannot be null")
        values.append(("model_json", model_json))

    if "response" in record:
        response = record["response"]
        if isinstance(response, dict) and {"raw_text", "model_json"} & response.keys():
            nested_raw_text, nested_model_json = _agent_model_json(response, prompt_id)
            values.append(("response", nested_model_json))
            if raw_text is None:
                raw_text = nested_raw_text
        elif isinstance(response, str):
            parsed = _parse_model_json(response)
            if parsed is None:
                raise ValueError(f"offline response {prompt_id} response is not valid JSON")
            values.append(("response", parsed))
            if raw_text is None:
                raw_text = response
        else:
            values.append(("response", response))

    if not values and "claims" in record:
        values.append(("claims", {"claims": record["claims"]}))

    if not values:
        raise ValueError(
            f"offline response {prompt_id} must contain raw_text, model_json, response, or claims"
        )
    expected = values[0][1]
    if any(value != expected for _, value in values[1:]):
        fields = ", ".join(name for name, _ in values)
        raise ValueError(f"offline response {prompt_id} has inconsistent JSON fields: {fields}")
    if "claims" in record and (
        not isinstance(expected, dict) or expected.get("claims") != record["claims"]
    ):
        raise ValueError(f"offline response {prompt_id} claims do not match model_json")
    if not isinstance(expected, dict) or not isinstance(expected.get("claims"), list):
        raise ValueError(f"offline response {prompt_id} model JSON requires a claims list")
    if any(not isinstance(claim, dict) for claim in expected["claims"]):
        raise ValueError(f"offline response {prompt_id} claims must contain only objects")
    if raw_text is None:
        raw_text = _canonical_json_text(expected)
    return raw_text, expected


def _agent_not_evaluated(record: dict[str, object], prompt_id: str) -> tuple[str, str] | None:
    """Normalise an explicit per-unit not_evaluated/failed declaration.

    The canonical ``merge`` path already accepts ``status: not_evaluated`` with a
    reason, but the offline agent-file adapter required parseable claims JSON.
    A researcher may legitimately return no judgment for a unit (not judged,
    which is not the same as judged-no-bridge), so the same declaration is
    accepted here and preserved as a non-claim response. Contradictory payloads
    stay rejected; nothing is repaired.
    """
    status = str(record.get("status", "")).strip()
    if status not in {"not_evaluated", "failed"}:
        return None
    for key in ("raw_text", "model_json", "response", "claims"):
        value = record.get(key)
        if value not in (None, "", [], {}):
            raise ValueError(
                f"offline response {prompt_id} declares status={status} but also supplies {key}"
            )
    reason = str(record.get("reason") or record.get("not_evaluated_reason") or "").strip()
    if not reason:
        raise ValueError(f"offline response {prompt_id} declares status={status} without a reason")
    return status, reason


def _run_agent_file(
    prompts_path: Path,
    out_dir: Path,
    agent_path: Path,
    model: str,
    canonical_route_b_bundle: Path | None,
) -> dict[str, object]:
    """Normalize an offline Codex/OpenCode artifact into the llm-run contract."""
    prompt_sha256 = _sha256_file(prompts_path)
    prompts: list[dict[str, object]] = []
    for line_number, line in enumerate(prompts_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        record = json.loads(line)
        if not isinstance(record, dict) or not {"prompt_id", "gene_id", "system", "user"}.issubset(record):
            raise ValueError(f"invalid prompt JSONL record at line {line_number}")
        prompts.append(record)
    prompt_ids = [str(prompt["prompt_id"]) for prompt in prompts]
    if len(set(prompt_ids)) != len(prompt_ids):
        raise ValueError("prompt JSONL contains duplicate prompt_id values")

    records = _agent_response_records(_read_agent_payload(agent_path))
    normalized_by_prompt: dict[str, dict[str, object]] = {}
    for index, value in enumerate(records, 1):
        if not isinstance(value, dict) or not str(value.get("prompt_id", "")).strip():
            raise ValueError(f"offline response row {index} requires prompt_id")
        prompt_id = str(value["prompt_id"])
        if prompt_id in normalized_by_prompt:
            raise ValueError(f"offline agent file contains duplicate prompt_id: {prompt_id}")
        declared = _agent_not_evaluated(value, prompt_id)
        if declared is not None:
            status, reason = declared
            normalized_by_prompt[prompt_id] = {
                "prompt_id": prompt_id,
                "gene_id": str(value.get("gene_id", "")),
                "claims": [],
                "model_json": None,
                "raw_text": "",
                "parse_status": "not_evaluated",
                "review_status": "not_evaluated",
                "not_evaluated_reason": reason,
                "declared_status": status,
                # route_b_response_state reads the researcher's own declaration here.
                "agent_response_raw": value,
                **({"route_b_unit_id": str(value["route_b_unit_id"])} if "route_b_unit_id" in value else {}),
            }
            continue
        raw_text, model_json = _agent_model_json(value, prompt_id)
        candidate: dict[str, object] = {
            "prompt_id": prompt_id,
            "gene_id": str(value.get("gene_id", "")),
            "claims": model_json.get("claims", []) if isinstance(model_json, dict) else [],
            "model_json": model_json,
            "raw_text": raw_text,
            # ``ok`` was used by agent-authored artifacts; emit canonical json
            # only after the deterministic parse and consistency checks above.
            "parse_status": "json",
            "review_status": "not_reviewed",
        }
        if "route_b_unit_id" in value:
            candidate["route_b_unit_id"] = str(value["route_b_unit_id"])
        normalized_by_prompt[prompt_id] = candidate

    expected_ids = set(prompt_ids)
    actual_ids = set(normalized_by_prompt)
    if actual_ids != expected_ids:
        missing = sorted(expected_ids - actual_ids)
        extra = sorted(actual_ids - expected_ids)
        raise ValueError(
            "offline agent response roster must exactly match prompts; "
            f"missing={missing}, extra={extra}"
        )
    normalized: list[dict[str, object]] = []
    for prompt in prompts:
        prompt_id = str(prompt["prompt_id"])
        candidate = normalized_by_prompt[prompt_id]
        supplied_gene = str(candidate.get("gene_id", ""))
        expected_gene = str(prompt["gene_id"])
        if supplied_gene and supplied_gene != expected_gene:
            raise ValueError(
                f"offline response {prompt_id} gene_id mismatch: {supplied_gene!r} != {expected_gene!r}"
            )
        candidate["gene_id"] = expected_gene
        prompt_route_unit = str(prompt.get("route_b_unit_id", ""))
        response_route_unit = str(candidate.get("route_b_unit_id", ""))
        if prompt_route_unit and response_route_unit and prompt_route_unit != response_route_unit:
            raise ValueError(
                f"offline response {prompt_id} route_b_unit_id mismatch: "
                f"{response_route_unit!r} != {prompt_route_unit!r}"
            )
        normalized.append(candidate)

    out_dir.mkdir(parents=True, exist_ok=True)
    raw_target = out_dir / f"llm_agent_raw_artifact{agent_path.suffix or '.json'}"
    if raw_target.resolve() != agent_path.resolve():
        shutil.copyfile(agent_path, raw_target)
    normalized_path = out_dir / "llm_candidate_responses.json"
    normalized_bytes = (json.dumps({"candidates": normalized}, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    normalized_path.write_bytes(normalized_bytes)
    response_sha256 = hashlib.sha256(normalized_bytes).hexdigest()
    raw_agent_artifact_sha256 = _sha256_file(agent_path)
    manifest: dict[str, object] = {
        "provider": "codex-agent",
        "model": model,
        "endpoint": "",
        "external_api": False,
        "offline_agent_file": True,
        "prompt_count": len(prompts),
        "raw_responses": None,
        "normalized_responses": str(normalized_path),
        "agent_file": str(agent_path),
        "raw_agent_artifact": str(raw_target),
        "agent_file_sha256": raw_agent_artifact_sha256,
        "raw_agent_artifact_sha256": raw_agent_artifact_sha256,
        "prompt_sha256": prompt_sha256,
        "response_sha256": response_sha256,
        "prompt_roster_exact": True,
        "warning": "Responses are unreviewed research notes and are not scoring evidence. Verify sources, set reviewed=true claim-by-claim, then use semantic import.",
    }
    manifest.update(response_execution_evidence(normalized))
    if canonical_route_b_bundle is not None:
        manifest.update(
            {
                "canonical_route_b_semantic": True,
                "bundle": str(canonical_route_b_bundle),
                "bundle_sha256": _sha256_file(canonical_route_b_bundle),
            }
        )
    manifest_path = out_dir / "llm_run_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return manifest | {"manifest": str(manifest_path)}


def run_llm_prompts(
    prompts_arg: str,
    out_dir_arg: str,
    provider: str,
    model: str,
    endpoint: str | None = None,
    api_key_env: str = "OPENAI_API_KEY",
    allow_external_api: bool = False,
    max_output_tokens: int = 2500,
    timeout: int = 180,
    agent_file: str | None = None,
) -> dict[str, object]:
    """Run prompts through a provider, or normalize one offline agent artifact."""
    if provider not in {"openai-responses", "openai-compatible", "lmstudio-cli", "codex-agent"}:
        raise ValueError("provider must be openai-responses, openai-compatible, lmstudio-cli, or codex-agent")
    if not model:
        raise ValueError("model is required")
    if max_output_tokens < 100:
        raise ValueError("max_output_tokens must be at least 100")
    if provider == "codex-agent":
        if not agent_file:
            raise ValueError("codex-agent provider requires --agent-file")
        if endpoint:
            raise ValueError("codex-agent offline mode does not accept --endpoint")
        prompts_path = runtime_path(prompts_arg)
        agent_path = runtime_path(agent_file)
        if not agent_path.exists() or not agent_path.is_file():
            raise ValueError(f"offline agent file does not exist: {agent_path}")
        canonical_route_b_bundle = None
        if prompts_path.name == _CANONICAL_ROUTE_B_PROMPTS_NAME:
            canonical_route_b_bundle = prompts_path.with_name(_CANONICAL_ROUTE_B_BUNDLE_NAME)
            if not canonical_route_b_bundle.exists():
                raise ValueError(
                    "canonical Route B semantic prompts require sibling "
                    f"{_CANONICAL_ROUTE_B_BUNDLE_NAME}: {canonical_route_b_bundle}"
                )
        return _run_agent_file(prompts_path, runtime_path(out_dir_arg), agent_path, model, canonical_route_b_bundle)
    if agent_file:
        raise ValueError("--agent-file is only valid with --provider codex-agent")
    endpoint = endpoint or (
        "https://api.openai.com/v1/responses"
        if provider == "openai-responses"
        else "http://127.0.0.1:1234/v1/chat/completions" if provider == "openai-compatible"
        else "lms"
    )
    if provider != "lmstudio-cli" and not _is_loopback(endpoint) and not allow_external_api:
        raise ValueError("external endpoint blocked; inspect prompts and pass --allow-external-api explicitly")
    api_key = os.environ.get(api_key_env, "")
    if provider == "openai-responses" and not api_key:
        raise ValueError(f"API key environment variable is not set: {api_key_env}")

    prompts_path = runtime_path(prompts_arg)
    out_dir = runtime_path(out_dir_arg)
    out_dir.mkdir(parents=True, exist_ok=True)
    canonical_route_b_bundle: Path | None = None
    if prompts_path.name == _CANONICAL_ROUTE_B_PROMPTS_NAME:
        canonical_route_b_bundle = prompts_path.with_name(_CANONICAL_ROUTE_B_BUNDLE_NAME)
        if not canonical_route_b_bundle.exists():
            raise ValueError(
                "canonical Route B semantic prompts require sibling "
                f"{_CANONICAL_ROUTE_B_BUNDLE_NAME}: {canonical_route_b_bundle}"
            )
    prompt_sha256 = _sha256_file(prompts_path)
    prompts: list[dict[str, object]] = []
    for line_number, line in enumerate(prompts_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        record = json.loads(line)
        if not isinstance(record, dict) or not {"prompt_id", "gene_id", "system", "user"}.issubset(record):
            raise ValueError(f"invalid prompt JSONL record at line {line_number}")
        prompts.append(record)

    raw_path = out_dir / "llm_raw_responses.jsonl"
    normalized: list[dict[str, object]] = []
    with raw_path.open("w", encoding="utf-8") as raw_handle:
        for prompt in prompts:
            if provider == "lmstudio-cli":
                completed = subprocess.run(
                    [
                        endpoint, "chat", model, "-p", str(prompt["user"]),
                        "-s", str(prompt["system"]), "--reasoning", "off", "-y",
                    ],
                    capture_output=True, text=True, timeout=timeout, check=False,
                    env={**os.environ, "NO_COLOR": "1", "TERM": "dumb", "COLUMNS": "100000"},
                )
                if completed.returncode != 0:
                    raise RuntimeError(f"LM Studio CLI failed: {completed.stderr.strip()[:500]}")
                response_payload = {
                    "choices": [{"message": {"content": completed.stdout.strip()}}],
                    "provider": "lmstudio-cli",
                }
            elif provider == "openai-responses":
                body = {
                    "model": model,
                    "instructions": prompt["system"],
                    "input": prompt["user"],
                    "max_output_tokens": max_output_tokens,
                    "store": False,
                }
            else:
                body = {
                    "model": model,
                    "messages": [
                        {"role": "system", "content": prompt["system"]},
                        {"role": "user", "content": prompt["user"]},
                    ],
                    "max_tokens": max_output_tokens,
                    "temperature": 0,
                }
            if provider != "lmstudio-cli":
                headers = {"Content-Type": "application/json"}
                if api_key:
                    headers["Authorization"] = f"Bearer {api_key}"
                request = urllib.request.Request(endpoint, json.dumps(body).encode("utf-8"), headers=headers, method="POST")
                try:
                    with urllib.request.urlopen(request, timeout=timeout) as response:
                        response_payload = json.loads(response.read().decode("utf-8"))
                except urllib.error.HTTPError as error:
                    detail = error.read().decode("utf-8", errors="replace")
                    raise RuntimeError(f"LLM API HTTP {error.code}: {detail[:500]}") from error
                except urllib.error.URLError as error:
                    raise RuntimeError(f"LLM API connection failed: {error.reason}") from error
            text = _response_text(provider, response_payload)
            parsed = _parse_model_json(text)
            if isinstance(parsed, dict) and isinstance(parsed.get("claims"), list):
                for claim in parsed["claims"]:
                    if isinstance(claim, dict):
                        claim["reviewed"] = False
            raw_handle.write(json.dumps({"prompt_id": prompt["prompt_id"], "gene_id": prompt["gene_id"], "response": response_payload}, ensure_ascii=False) + "\n")
            normalized.append(
                {
                    "prompt_id": prompt["prompt_id"],
                    "gene_id": prompt["gene_id"],
                    "claims": parsed.get("claims", []) if isinstance(parsed, dict) else [],
                    "model_json": parsed,
                    "raw_text": text,
                    "parse_status": "json" if parsed is not None else "unparsed_text",
                    "review_status": "not_reviewed",
                }
            )
    normalized_path = out_dir / "llm_candidate_responses.json"
    normalized_path.write_text(json.dumps({"candidates": normalized}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    manifest = {
        "provider": provider,
        "model": model,
        "endpoint": endpoint,
        "external_api": False if provider == "lmstudio-cli" else not _is_loopback(endpoint),
        "prompt_count": len(prompts),
        "raw_responses": str(raw_path),
        "normalized_responses": str(normalized_path),
        "warning": "Responses are unreviewed research notes and are not scoring evidence. Verify sources, set reviewed=true claim-by-claim, then use llm-evidence-import.",
    }
    manifest.update(response_execution_evidence(normalized))
    if canonical_route_b_bundle is not None:
        manifest.update(
            {
                "canonical_route_b_semantic": True,
                "bundle": str(canonical_route_b_bundle),
                "bundle_sha256": _sha256_file(canonical_route_b_bundle),
                "prompt_sha256": prompt_sha256,
                "response_sha256": _sha256_file(normalized_path),
            }
        )
    manifest_path = out_dir / "llm_run_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return manifest | {"manifest": str(manifest_path)}
